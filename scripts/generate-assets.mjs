// Generates self-owned (no third-party licence) assets:
//   public/env/studio.hdr     1024x512 equirectangular Radiance HDR (RLE), procedural softbox studio
//   public/poster.avif|.jpg   1600x1000 hero poster matching the scene's first frame
//   public/poster-mobile.avif 900x1125 designed mobile composition (+ -dark variants of both)
//   public/placeholder/NN.svg 12 abstract 4:5 placeholder compositions (layout review only)
// Usage: npm run assets
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
mkdirSync(join(pub, 'env'), { recursive: true });
mkdirSync(join(pub, 'placeholder'), { recursive: true });

// ---------- HDR ----------
const W = 1024, H = 512;
function softbox(u, v, cu, cv, hw, hh, feather) {
  // u, v in [0,1); returns 0..1 with soft edges (u wraps).
  let du = Math.abs(u - cu); du = Math.min(du, 1 - du);
  const dv = Math.abs(v - cv);
  const fu = Math.min(1, Math.max(0, (hw - du) / feather + 0.5));
  const fv = Math.min(1, Math.max(0, (hh - dv) / feather + 0.5));
  return fu * fv;
}
function radiance(u, v) {
  // v = 0 top (zenith), 1 bottom (nadir). A product-photography studio for a flat-faced metal
  // object: a broad, moderate gradient (brighter toward the key side and the ceiling) so each
  // face reflects a distinct mid-tone, plus small softboxes that read as edge highlights.
  // Shaped at unit scale, then multiplied by k below; tuned against the hero poster.
  const side = 0.7 + 0.3 * Math.cos(2 * Math.PI * (u - 0.33)); // 1.0 toward the key, 0.4 opposite
  const sky = (0.42 - 0.26 * Math.min(1, v / 0.55)) * side;
  const floor = v > 0.55 ? (0.12 + (v - 0.55) * 0.05) * (0.85 + 0.15 * side) : 0;
  const base = v > 0.55 ? floor : sky;
  let r = base * 1.04, g = base, b = base * 0.9;
  const top = softbox(u, v, 0.5, 0.1, 0.18, 0.05, 0.04) * 1.1; // overhead
  const key = softbox(u, v, 0.33, 0.42, 0.035, 0.15, 0.025) * 1.3; // key strip, warm
  const fill = softbox(u, v, 0.72, 0.45, 0.06, 0.1, 0.05) * 0.35; // fill, neutral
  const rim = softbox(u, v, 0.93, 0.38, 0.012, 0.18, 0.01) * 1.0; // rim strip
  r += top + key + fill + rim;
  g += top + key * 0.92 + fill + rim;
  b += top + key * 0.79 + fill * 1.02 + rim;
  const k = 3.1; // overall exposure of the studio, tuned against the poster's bronze tones
  return [r * k, g * k, b * k];
}
function rgbe([r, g, b]) {
  const v = Math.max(r, g, b);
  if (v < 1e-32) return [0, 0, 0, 0];
  const e = Math.ceil(Math.log2(v) + 1e-9);
  const s = 256 / 2 ** e;
  return [Math.min(255, Math.floor(r * s)), Math.min(255, Math.floor(g * s)), Math.min(255, Math.floor(b * s)), e + 128];
}
const header = Buffer.from(`#?RADIANCE\n# Bronze Standard procedural studio (self-generated, no third-party licence)\nFORMAT=32-bit_rle_rgbe\n\n-Y ${H} +X ${W}\n`, 'ascii');
const chunks = [header];
for (let y = 0; y < H; y++) {
  const ch = [[], [], [], []];
  for (let x = 0; x < W; x++) {
    const p = rgbe(radiance((x + 0.5) / W, (y + 0.5) / H));
    for (let c = 0; c < 4; c++) ch[c].push(p[c]);
  }
  const line = [2, 2, W >> 8, W & 255];
  for (let c = 0; c < 4; c++) {
    // New-style RLE per channel: runs (128 + n, value) for n >= 3 repeats, literals (n, bytes...) otherwise.
    const d = ch[c];
    let i = 0;
    while (i < W) {
      let run = 1;
      while (i + run < W && run < 127 && d[i + run] === d[i]) run++;
      if (run >= 3) {
        line.push(128 + run, d[i]);
        i += run;
        continue;
      }
      const start = i;
      let n = 0;
      while (i < W && n < 128) {
        let r = 1;
        while (i + r < W && r < 3 && d[i + r] === d[i]) r++;
        if (r >= 3) break;
        i++;
        n++;
      }
      line.push(n, ...d.slice(start, start + n));
    }
  }
  chunks.push(Buffer.from(line));
}
writeFileSync(join(pub, 'env', 'studio.hdr'), Buffer.concat(chunks));
writeFileSync(join(pub, 'env', 'LICENSE.txt'), 'studio.hdr is generated by scripts/generate-assets.mjs for Bronze Standard. No third-party content; no licence restrictions.\n');

// ---------- Posters ----------
const obelisk = (cx, base, h, w) => {
  const top = base - h, capH = h * 0.17, shaftTop = top + capH, tw = w * 0.72;
  return `
  <defs>
    <linearGradient id="face-l" x1="0" x2="1"><stop offset="0" stop-color="#6E5230"/><stop offset="0.55" stop-color="#B08D57"/><stop offset="1" stop-color="#E2C99E"/></linearGradient>
    <linearGradient id="face-r" x1="0" x2="1"><stop offset="0" stop-color="#9C7A48"/><stop offset="1" stop-color="#4A3720"/></linearGradient>
    <linearGradient id="cap" x1="0" x2="1"><stop offset="0" stop-color="#F0DDB8"/><stop offset="1" stop-color="#8C6B3F"/></linearGradient>
    <radialGradient id="shadow" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#0A0A0B" stop-opacity="0.18"/><stop offset="1" stop-color="#0A0A0B" stop-opacity="0"/></radialGradient>
  </defs>
  <ellipse cx="${cx}" cy="${base + 8}" rx="${w * 1.6}" ry="${w * 0.22}" fill="url(#shadow)"/>
  <polygon points="${cx - w},${base} ${cx},${base + w * 0.12} ${cx},${shaftTop + tw * 0.1} ${cx - tw},${shaftTop}" fill="url(#face-l)"/>
  <polygon points="${cx},${base + w * 0.12} ${cx + w},${base} ${cx + tw},${shaftTop} ${cx},${shaftTop + tw * 0.1}" fill="url(#face-r)"/>
  <polygon points="${cx - tw},${shaftTop} ${cx},${shaftTop + tw * 0.1} ${cx},${top}" fill="url(#cap)"/>
  <polygon points="${cx},${shaftTop + tw * 0.1} ${cx + tw},${shaftTop} ${cx},${top}" fill="#7A5C34"/>`;
};
const poster = (w, h, floorY, cx, base, oh, ow, bg, floor) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <rect width="${w}" height="${h}" fill="${bg}"/>
  <rect y="${floorY}" width="${w}" height="${h - floorY}" fill="${floor}"/>
  ${obelisk(cx, base, oh, ow)}
</svg>`;
const variants = [
  ['poster', 1600, 1000, 760, 1130, 770, 600, 80],
  ['poster-mobile', 900, 1125, 820, 620, 830, 640, 84],
];
for (const [name, w, h, fy, cx, base, oh, ow] of variants) {
  const light = Buffer.from(poster(w, h, fy, cx, base, oh, ow, '#F6F3EE', '#EDE8E0'));
  const dark = Buffer.from(poster(w, h, fy, cx, base, oh, ow, '#0A0A0B', '#16161A'));
  await sharp(light).avif({ quality: 55, effort: 6 }).toFile(join(pub, `${name}.avif`));
  await sharp(dark).avif({ quality: 55, effort: 6 }).toFile(join(pub, `${name}-dark.avif`));
  if (name === 'poster') await sharp(light).jpeg({ quality: 80, mozjpeg: true }).toFile(join(pub, 'poster.jpg'));
}

// ---------- Placeholders (abstract, clearly not photographs) ----------
const tones = ['#EDE8E0', '#DDD6CA', '#16161A', '#3A3A42'];
for (let i = 1; i <= 12; i++) {
  const bg = tones[i % 4];
  const dark = bg === '#16161A' || bg === '#3A3A42';
  const fg = dark ? '#D6BC92' : '#8C6B3F';
  const ink = dark ? '#F6F3EE' : '#0A0A0B';
  const a = 120 + ((i * 47) % 380), b = 180 + ((i * 83) % 520);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="1000" viewBox="0 0 800 1000">
  <rect width="800" height="1000" fill="${bg}"/>
  <circle cx="${a + 120}" cy="${b}" r="${140 + (i % 3) * 40}" fill="none" stroke="${fg}" stroke-width="1.5"/>
  <rect x="${80 + (i % 4) * 40}" y="${620 - (i % 5) * 30}" width="${260 + (i % 3) * 60}" height="2" fill="${ink}" fill-opacity="0.5"/>
  <text x="64" y="940" font-family="monospace" font-size="20" letter-spacing="3" fill="${ink}" fill-opacity="0.6">PLACEHOLDER ${String(i).padStart(2, '0')}</text>
</svg>`;
  writeFileSync(join(pub, 'placeholder', `${String(i).padStart(2, '0')}.svg`), svg);
}
